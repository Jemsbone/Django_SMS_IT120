if use_sqlite:
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': BASE_DIR / 'db.sqlite3',
        }
    }
else:
    # Supports both Django format (DB_NAME, DB_USER) and Laravel format (DB_DATABASE, DB_USERNAME)
    db_name = os.getenv('DB_NAME') or os.getenv('DB_DATABASE') or 'sms_db'
